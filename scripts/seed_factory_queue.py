"""seed_factory_queue — generate intent alloys for the BigMama queue.

The published alloys (e.g. qwen3-coder-30b-a3b-compacted-19b-256k) are
huge because they include model-card prose, methodology blockquotes, all
the priorMetricBaselines, etc. That stuff is published-form metadata,
generated by the publish stage AFTER the forge runs.

For queueing the next batch of forges, we want INTENT recipes: minimal,
authored once, dispatchable through alloy_executor + the family-adapter
set + the eval-runner registry. This script is the per-target catalog of
intent recipes — Kash's frontier-target list materialized as files in
.factory/line/intake/.

Each candidate is one Python dict with the four fields the forge needs:
    name              — what continuum-ai/<name> will be on HF
    base_model        — HF id of the source model
    architecture      — source.architecture string (matches FamilyAdapter)
    forge             — the prune target + eval benchmarks for this family

The script renders each candidate to a minimal alloy JSON and copies it
into .factory/line/intake/. From there factory_queue.FactoryWorker
picks them up.

Usage:
    python scripts/seed_factory_queue.py --root .factory --dry-run
    python scripts/seed_factory_queue.py --root .factory   # actually enqueue

The list is the empty-quadrant viral targets Kash mapped:
  Mixtral 8x22B  — single-5090 prosumer headline
  Mixtral 8x7B   — smaller sibling, same layout
  Phi-3.5-MoE    — same layout, 16 experts/layer
  DeepSeek-V2-Lite — routed + shared (shared bit-exact)
  OLMoE-1B-7B    — Qwen3MoE-layout sibling, second §4.1.3.4 anchor
  Qwen3-Coder-30B-A3B — re-publish via the new pipeline (sanity check)
  Qwen3-VL-30B-A3B — VL MoE (vision_safety + MoE pruner together)
  Qwen3-VL-8B     — pure VL forge
  Qwen2.5-Omni-7B — 4-tower omni (vision + audio + talker + token2wav)
"""

