def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", default=".factory", help="queue root directory")
    ap.add_argument("--dry-run", action="store_true", help="print, do not enqueue")
    args = ap.parse_args()

    root = Path(args.root)
    if not args.dry_run:
        queue = FactoryQueue(root)

    print(f"factory queue catalog: {len(CATALOG)} candidates")
    for i, alloy in enumerate(CATALOG, start=1):
        name = alloy["name"]
        base = alloy["source"]["baseModel"]
        arch = alloy["source"]["architecture"]
        is_moe = alloy["source"].get("isMoE", False)
        flag = "MoE" if is_moe else "dense"
        print(f"  {i}. {name}")
        print(f"     ← {base}  ({arch}, {flag})")

        if args.dry_run:
            continue

        # Write to a temp path then enqueue.
        tmp = root / f"_seed_{name}.alloy.json"
        tmp.parent.mkdir(parents=True, exist_ok=True)
        tmp.write_text(json.dumps(alloy, indent=2))
        try:
            enqueued = queue.enqueue(tmp)
            print(f"     → enqueued at {enqueued.relative_to(root)}")
        finally:
            tmp.unlink(missing_ok=True)

    if not args.dry_run:
        print(f"\nfinal stats: {queue.stats()}")
        print(f"start the worker: python -m factory_queue --root {args.root} --max-iters {len(CATALOG)}")


if __name__ == "__main__":
    main()
